/**
 * Citation Validation & Provenance Verification Engine
 * Audits LLM-generated outputs to verify that every citation tag [DOC-...] 
 * matches retrieved chunks and accurately reflects ground-truth context.
 */

import { CitationReference, RetrievalResult } from '../types';

export class CitationValidatorService {
  /**
   * Parses citation tags from answer text and cross-references with retrieved evidence
   */
  public validateCitations(
    answerText: string,
    retrievedResults: RetrievalResult[]
  ): {
    citations: CitationReference[];
    validityScore: number;
    unsupportedClaims: string[];
  } {
    // Regex matching [DOC-...] or [CHUNK-...] citations
    const citationRegex = /\[(DOC-[A-Z0-9-]+|CHUNK-[A-Z0-9-]+)\]/g;
    const matches = Array.from(answerText.matchAll(citationRegex));

    const retrievedMap = new Map<string, RetrievalResult>();
    retrievedResults.forEach(res => {
      retrievedMap.set(res.docMetadata.id, res);
      retrievedMap.set(res.chunk.id, res);
    });

    const citationMap = new Map<string, CitationReference>();
    const unsupportedClaims: string[] = [];

    matches.forEach(match => {
      const citeTag = match[0];
      const matchedId = match[1];

      if (citationMap.has(citeTag)) return; // Deduplicate

      const matchedResult = retrievedMap.get(matchedId);

      if (matchedResult) {
        // Extract surrounding sentence context for claim verification
        const sentence = this.extractSentenceAroundTag(answerText, match.index ?? 0);

        citationMap.set(citeTag, {
          citationId: citeTag,
          chunkId: matchedResult.chunk.id,
          docTitle: matchedResult.docMetadata.title,
          issuer: matchedResult.docMetadata.issuer,
          jurisdiction: matchedResult.docMetadata.jurisdiction,
          sectionTitle: matchedResult.chunk.sectionTitle,
          pageLocator: matchedResult.chunk.pageLocator,
          url: matchedResult.docMetadata.canonicalUrl,
          version: matchedResult.docMetadata.version,
          isVerified: true,
          supportSnippet: matchedResult.chunk.content.slice(0, 280) + '...',
          claimText: sentence
        });
      } else {
        // Unmatched citation hallucinated by LLM
        unsupportedClaims.push(`Citation ${citeTag} was generated by the LLM but does not exist in the retrieved evidence corpus.`);
        
        citationMap.set(citeTag, {
          citationId: citeTag,
          chunkId: 'UNKNOWN',
          docTitle: 'UNVERIFIED SOURCE',
          issuer: 'FDA',
          jurisdiction: 'US',
          sectionTitle: 'Unverified Citation',
          pageLocator: 'N/A',
          url: '#',
          version: 'N/A',
          isVerified: false,
          supportSnippet: 'This citation tag could not be verified against the active evidence corpus.',
          claimText: 'Ungrounded claim'
        });
      }
    });

    const totalCitations = citationMap.size;
    let verifiedCount = 0;
    citationMap.forEach(c => {
      if (c.isVerified) verifiedCount++;
    });

    const validityScore = totalCitations > 0 ? Math.round((verifiedCount / totalCitations) * 100) : 100;

    return {
      citations: Array.from(citationMap.values()),
      validityScore,
      unsupportedClaims
    };
  }

  private extractSentenceAroundTag(text: string, index: number): string {
    const start = Math.max(0, text.lastIndexOf('.', index) + 1);
    let end = text.indexOf('.', index);
    if (end === -1) end = text.length;
    return text.substring(start, end).trim();
  }
}

export const citationValidator = new CitationValidatorService();
